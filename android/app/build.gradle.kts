import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
}

android {
    namespace = "se.eyevinn.tallycam"
    compileSdk = 35

    defaultConfig {
        applicationId = "se.eyevinn.tallycam"
        // Android 10: Opus in MediaCodec.
        minSdk = 29
        targetSdk = 35
        versionCode = 3
        versionName = "0.3.0"
        ndk {
            // The core is built for these (scripts/build-core-android.sh).
            abiFilters += listOf("arm64-v8a")
        }
    }

    // Release signing from android/keystore.properties (not in git):
    // storeFile, storePassword, keyAlias, keyPassword. Without it a release
    // build is unsigned, or with -PallowDebugSigning signed with the debug
    // key, for local testing only.
    val keystore = rootProject.file("keystore.properties").takeIf { it.exists() }?.let { file ->
        Properties().apply { file.inputStream().use { load(it) } }
    }
    signingConfigs {
        if (keystore != null) {
            create("release") {
                storeFile = rootProject.file(keystore.getProperty("storeFile"))
                storePassword = keystore.getProperty("storePassword")
                keyAlias = keystore.getProperty("keyAlias")
                keyPassword = keystore.getProperty("keyPassword")
            }
        }
    }
    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            // Never a silent debug key on a release: whoever holds that
            // keystore could ship updates to it. -PallowDebugSigning for a
            // local release build.
            signingConfig = signingConfigs.findByName("release")
                ?: if (project.hasProperty("allowDebugSigning")) signingConfigs.getByName("debug")
                else null
        }
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    // The UniFFI Kotlin bindings of the core, generated by the build script.
    sourceSets["main"].java.srcDir("build/generated/uniffi")
}

// Builds the Rust core and its Kotlin bindings before anything compiles.
val buildCore by tasks.registering(Exec::class) {
    workingDir = rootDir.parentFile
    commandLine("scripts/build-core-android.sh", "arm64-v8a")
    // Up to date unless the core changed, so Kotlin does not recompile on
    // every build. -PskipCore: use the library and bindings already built.
    val repo = rootDir.parentFile
    inputs.files(fileTree(repo.resolve("core")) { include("**/*.rs", "**/Cargo.toml", "**/uniffi.toml") })
    inputs.files(repo.resolve("Cargo.toml"), repo.resolve("Cargo.lock"), repo.resolve("scripts/build-core-android.sh"))
    outputs.dir("src/main/jniLibs")
    outputs.dir("build/generated/uniffi")
    onlyIf { !project.hasProperty("skipCore") }
}
tasks.named("preBuild") { dependsOn(buildCore) }

